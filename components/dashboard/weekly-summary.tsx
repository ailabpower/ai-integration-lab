"use client";

import { useEffect, useState } from "react";
import type { SummaryResponse } from "@/app/api/dashboard/summary/route";

export function WeeklySummary() {
  const [data, setData] = useState<SummaryResponse | null>(null);
  const [error, setError] = useState(false);

  useEffect(() => {
    fetch("/api/dashboard/summary")
      .then((r) => (r.ok ? r.json() : Promise.reject()))
      .then(setData)
      .catch(() => setError(true));
  }, []);

  if (error) return null;
  return (
    <section className="mt-6 rounded-xl border border-[var(--accent)]/40 bg-[var(--surface)] p-4" aria-busy={!data}>
      <h2 className="text-sm font-medium">✦ AI weekly summary{data && <span className="ml-2 font-normal text-[var(--muted)]">{data.weekStart} – {data.weekEnd}</span>}</h2>
      <p className="mt-2 text-sm leading-relaxed">{data ? data.summary : "Reading last week's numbers…"}</p>
      {data && <p className="mt-2 text-xs text-[var(--muted)]">Generated by {data.model} from the same reports as this dashboard.</p>}
    </section>
  );
}
